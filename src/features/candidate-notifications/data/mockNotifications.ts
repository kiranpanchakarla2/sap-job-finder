/**
 * Creates dynamic timestamps relative to the current execution time
 * so date grouping ("Today", "Yesterday", "Earlier this week", "Earlier")
 * always operates accurately in any environment.
 */
function createRelativeIso(offsetMs: number): string {
  return new Date(Date.now() - offsetMs).toISOString();
}

