import { APPLICATION_STATUS_CONFIG } from "../constants";

function snap(
  partial: Omit<ApplicationJobSnapshot, "companyLogo" | "companyLogoColor"> & {
    companyLogo?: string;
    companyLogoColor?: string;
  },
): ApplicationJobSnapshot {
  return {
    companyLogo: partial.companyLogo ?? partial.companyName.slice(0, 1).toUpperCase(),
    companyLogoColor: partial.companyLogoColor ?? "#7C3AED",
    ...partial,
  };
}

function timeline(
  events: Array<{ status: CandidateApplication["status"]; timestamp: string }>,
): ApplicationTimelineEvent[] {
  return events.map((event) => ({
    status: event.status,
    timestamp: event.timestamp,
    label: APPLICATION_STATUS_CONFIG[event.status].label,
  }));
}

