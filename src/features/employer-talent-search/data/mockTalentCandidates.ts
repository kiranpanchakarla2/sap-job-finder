function cert(
  id: string,
  name: string,
  type: string,
  year: number,
): TalentCandidate["certifications"][number] {
  return { id, name, type, year };
}

function exp(
  id: string,
  company: string,
  role: string,
  startDate: string,
  endDate: string | null,
  description: string,
  skills: string[],
): TalentCandidate["experience"][number] {
  return { id, company, role, startDate, endDate, description, skills };
}

function edu(
  id: string,
  school: string,
  degree: string,
  field: string,
  year: number,
): TalentCandidate["education"][number] {
  return { id, school, degree, field, year };
}

