export function listActiveDiscoveryJobs(now = new Date()) {
  return MOCK_DISCOVERY_JOBS.filter((jobItem) => {
    if (jobItem.status !== "active") return false;
    if (jobItem.expiresAt && new Date(jobItem.expiresAt) < now) return false;
    return true;
  });
}
