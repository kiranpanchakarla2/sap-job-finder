import type { DiscoveryJob } from "../types/job.types";
import { MOCK_DISCOVERY_COMPANIES } from "./mockCompanies";

function company(id: string) {
  const c = MOCK_DISCOVERY_COMPANIES.find((item) => item.id === id);
  if (!c) throw new Error(`Unknown company: ${id}`);
  return c;
}

function job(
  partial: Omit<
    DiscoveryJob,
    | "companyName"
    | "companyLogo"
    | "companyLogoColor"
    | "companyDescription"
    | "companyLocation"
    | "industry"
    | "companySize"
    | "salaryCurrency"
    | "status"
    | "locations"
    | "expiresAt"
  > &
    Partial<
      Pick<
        DiscoveryJob,
        | "status"
        | "locations"
        | "salaryCurrency"
        | "expiresAt"
        | "featured"
      >
    >,
): DiscoveryJob {
  const c = company(partial.companyId);
  return {
    ...partial,
    salaryCurrency: "INR",
    status: partial.status ?? "active",
    locations: partial.locations ?? [partial.location.split(",")[0]?.trim() || partial.location],
    expiresAt: partial.expiresAt ?? null,
    featured: partial.featured,
    companyName: c.name,
    companyLogo: c.logo,
    companyLogoColor: c.logoColor,
    companyDescription: c.description,
    companyLocation: c.location,
    industry: c.industry,
    companySize: c.companySize,
  };
}

